package day07;

public class Class01 {
	
	//메서드 선언 가능 위치
	/* 두 정수를 받아(매개변수) 합을 리턴하는 매서드
	 * 리턴타입 : 합 (정수의 합) =int
	 * 매서드 : sum(이름 상관없음)
	 * 매개변수 : 두 정수 (변수만 선언하듯이) -> int a, int b
	 */
	public int sum(int a, int b) {
		return a+b;
	} 
	
	
	
	/* 두 점수를 입력받아(매개변수) 차를 리턴하는 메서드
	 * 리턴타입 : 차(정수) int
	 *  메서드명 : sub
	 *  매개변수 : 두 정수 => int a, int b
	 * 
	 */
	public int sub(int a, int b) {
		return a-b;
	} 
	
	//메서드 호출 (아무나 가능)
	/* 
	 * 
	 */
	public static void main(String[] args) {
		int num1 = 1;
		int num2 = 2;
		
		//같은 클래스 안의 메서드를 호출, 메서드명을 이용하여 호출
		//static : 일반 메서드 호출 불가 (static이 붙은 메서드만 호출가능)
		// 같은 클래스라도 객체를 생성해야 호출가능
		//일반 메서드는 객체 생성없이 호출가능(같은 클래스라면)
		
		// 다른 클래스는 반드시 객체를 생성해야 가능.
		
		// 객체생성 할 때는
		// 클래스명 객체명 = new 클래스명();
		//객채명. 메서드명(매개변수)
		Class01 c = new Class01();
		int sum = c.sum(num1, num2);
		System.out.println(sum);
		
		int sub = c.sub(num1, num2);
		System.out.println(sub);
	
		
		
		
	}
	
	
	// 클래스 : 멤버변수( 가지는 요소), 메서드 (해야하는 기능)
	// main method: 컴파일러가 실행을 위해 제일 먼저 찾는 메서드
	// 
	//멤버변수의 위치 (클래스 안, 메서드 밖)
	/* 메서드의 위치 : 멤버변수 다음 , 순서는 상관없음 -> 호출되야 실행
	 * 
	 *  메서드 구조
	 *  접근제어자(public) - 리턴 타입 - 메서드 명(매개변수) {
	 *  구현;
	 *  return 변수명 (있을 수도 없을 수도)
	 *  //return의 변수명은 반드시 리턴타입과 타입이 일치
	 *  
	 *   }
	 *   
	 *   
	 *   접근제어자: 접근할 수 있는 주체의 제한범위
	 *   public(누구나 접근) - 메서드
	 *   default (같은 패키지에 있는 클래스에만 접근 가능)
	 *   protected (같은 패키지+상속)
	 *   private (나만) - 멤서변수
	 *   
	 *   
	 *   리턴 타입: 메서드가 종료되고난 후에 (처리가 완료되고난 후) 반환 값 => 반드시 1개
	 *   반환값이 얼을 수도 있는데
	 *   void 를 사용.
	 *   
	 *   
	 *   메서드명 : 소문자로 시작(여러 의미를 붙여서 사용할 경우 카멜 케이스 사용)
	 *   매개변수 : =파라미터, 이 기능을 실행하기 위해 외부에서 받는 값 
	 *   - 여러개 가능 , 없어도 됨
	 *   값이 없어도 되지만 () 는 꼭 써야함
	 *   
	 *  return : 키워드; 메서드를 종료하는 키워드
	 *  리턴 타입과 일치는 리턴값을 주고 종료
	 *  void는 없음
	 *  
	 *   
	 *   메서드는 중복 선언이 안됨.(이름이 같으면 안됨)]
	 *   매서드 안에 또 다른 메서드가 있을 수 없음
	 *   메서드 단위로 위치는 상관없음
	 *   메서드를 선언하는 위치는 클래스 안에 
	 *   다른 메서드는 밖
	 *   -> 그래야 메서드는 독립적으로 운영
	 *   순서는 상관없음
	 *   호출되어야 실행
	 *   
	 */
	
	
	
	
}
